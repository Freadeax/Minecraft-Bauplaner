import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { saveProjectScan, loadProjectScanOriginal } from '../apps/web/src/app/scanPersistence.ts';
import { createProject, createBackup, readBackup, checkProjectRecord, checkIntegrity, freezeRevision } from '../dist/domain/src/index.js';

const bytes = Uint8Array.from([31, 139, 8, 0, 255, 1]);
const hash = createHash('sha256').update(bytes).digest('hex');
const scan = { sourceSha256: hash, fileName: 'aufgenommen.schem', meta: null };
const importedAt = '2026-10-31T15:00:00.000Z';
const reference = { sha256: hash, fileName: scan.fileName, importedAt, revisionId: null, alignment: [10, -5, 3] };

function repository() {
  let stored = { ...createProject({ name: 'Baustelle' }), revision: 1 };
  const originals = new Map();
  let calls = 0;
  return {
    get project() { return stored; }, get calls() { return calls; }, originals,
    async getOriginal(sha) { return originals.get(sha) ?? null; },
    async applyBatch(batch) {
      calls++;
      const update = batch.projects[0];
      // Simulates the repository's documented atomic baseRevision guard.
      if (update.baseRevision !== stored.revision) throw new Error('RevisionConflictError');
      for (const original of batch.originals) originals.set(original.sha256, original);
      stored = { ...update.project, revision: stored.revision + 1 };
      return [stored];
    },
  };
}

test('scan original and project reference are saved together, preserving manual alignment and deduplicating history', async () => {
  const repo = repository();
  const first = await saveProjectScan(repo, repo.project, scan, bytes, reference.alignment, importedAt);
  assert.equal(first.revision, 2);
  assert.deepEqual(first.scanHistory, [reference]);
  assert.deepEqual(repo.originals.get(hash).bytes, bytes);
  assert.equal(first.progress && Object.keys(first.progress).length, 0, 'manual ticks are never generated by saving');
  const second = await saveProjectScan(repo, first, scan, bytes, [11, -5, 3], importedAt);
  assert.equal(second.scanHistory.length, 1);
  assert.deepEqual(second.scanHistory[0].alignment, [11, -5, 3]);
  assert.equal(repo.originals.size, 1);
});

test('a concurrent project revision rejects the transaction; original and history stay unchanged', async () => {
  const repo = repository(), stale = repo.project;
  await saveProjectScan(repo, stale, scan, bytes, reference.alignment, importedAt);
  const otherBytes = new Uint8Array([1, 2, 3]);
  const otherHash = createHash('sha256').update(otherBytes).digest('hex');
  await assert.rejects(saveProjectScan(repo, stale, { ...scan, sourceSha256: otherHash }, otherBytes, [0, 0, 0], importedAt), /RevisionConflict/);
  assert.equal(repo.originals.has(otherHash), false);
  assert.equal(repo.project.scanHistory.length, 1);
});

test('mismatching source hashes, foreign project metadata, unknown revisions and unsafe alignment never reach storage', async () => {
  const repo = repository();
  await assert.rejects(saveProjectScan(repo, repo.project, scan, new Uint8Array([0]), [0, 0, 0]), /Prüfsumme/);
  for (const meta of [{ projectId: 'another', revisionId: 'r' }, { projectId: repo.project.id, revisionId: 'unknown' }])
    await assert.rejects(saveProjectScan(repo, repo.project, { ...scan, meta }, bytes, [0, 0, 0]), /bekannten Revision/);
  await assert.rejects(saveProjectScan(repo, repo.project, scan, bytes, [0.5, 0, 0]), /Ausrichtung/);
  await assert.rejects(saveProjectScan(repo, repo.project, { ...scan, fileName: '' }, bytes, [0, 0, 0]), /Dateiname/);
  assert.equal(repo.calls, 0);
});

test('bridge scan references an existing frozen revision', async () => {
  const repo = repository();
  const frozen = freezeRevision(repo.project, 'Bauplan');
  const project = { ...frozen.project, revision: repo.project.revision };
  const saved = await saveProjectScan(repo, project, { ...scan, meta: { projectId: project.id, revisionId: frozen.revision.id } }, bytes, [0, 0, 0], importedAt);
  assert.equal(saved.scanHistory[0].revisionId, frozen.revision.id);
  assert.equal(checkProjectRecord(saved).id, saved.id);
});

test('source reload verifies bytes and rejects missing, damaged and incorrect-size originals', async () => {
  const original = { sha256: hash, bytes, size: bytes.length, fileName: 'original.schem' };
  const loaded = await loadProjectScanOriginal({ getOriginal: async () => original }, reference);
  assert.deepEqual(loaded.bytes, bytes); assert.equal(loaded.fileName, scan.fileName);
  await assert.rejects(loadProjectScanOriginal({ getOriginal: async () => null }, reference), /fehlt/);
  await assert.rejects(loadProjectScanOriginal({ getOriginal: async () => ({ ...original, bytes: new Uint8Array([0]) }) }, reference), /beschädigt/);
  await assert.rejects(loadProjectScanOriginal({ getOriginal: async () => ({ ...original, size: 999 }) }, reference), /beschädigt/);
});

test('scan source bytes survive project backup and restore; absent sources become explicit warnings', async () => {
  const repo = repository();
  const project = await saveProjectScan(repo, repo.project, scan, bytes, reference.alignment, importedAt);
  const source = { projects: [project], assets: [], versions: new Map(), getOriginal: sha => repo.getOriginal(sha) };
  const backup = await createBackup(source, 'project', [project.id]);
  assert.equal(backup.originals.length, 1);
  const restored = await readBackup(JSON.stringify(backup));
  assert.deepEqual(restored.projects[0].scanHistory, [reference]);
  assert.deepEqual(restored.originals[0].bytes, bytes);
  const missing = await createBackup({ ...source, getOriginal: async () => null }, 'all');
  assert.deepEqual(missing.missingOriginals, [hash]);
  assert.deepEqual((await readBackup(JSON.stringify(missing))).missingOriginals, [hash]);
});

test('malformed scan history is rejected on backup import; old projects remain valid', () => {
  const project = createProject({ name: 'Alt' });
  assert.equal(checkProjectRecord(project), project);
  for (const ref of [{ ...reference, sha256: 'bad' }, { ...reference, alignment: [0, 1] }, { ...reference, importedAt: 'bad' }, { ...reference, revisionId: 'missing' }])
    assert.throws(() => checkProjectRecord({ ...project, scanHistory: [ref] }), /Aufnahme/);
  assert.throws(() => checkProjectRecord({ ...project, scanHistory: [reference, reference] }), /doppelter Aufnahmehash/);
});

test('integrity treats scan sources as used and reports missing source bytes', async () => {
  const project = { ...createProject({ name: 'Test' }), scanHistory: [reference] };
  const report = await checkIntegrity({ projects: [project], assets: [], versions: [], originalHashes: [hash] });
  assert.equal(report.findings.some(f => f.code === 'ORIGINAL_UNUSED'), false);
  const missing = await checkIntegrity({ projects: [project], assets: [], versions: [], originalHashes: [] });
  assert.equal(missing.findings.some(f => f.code === 'ORIGINAL_MISSING'), true);
});
