#!/usr/bin/env node
// COMPAT-01: leitet aus den offiziellen Blockberichten älterer Minecraft-Versionen ab, was ein Plan des
// Versionsprofils dort verliert: Blöcke, die es noch nicht gibt, und Blöcke mit anderen Eigenschaften.
// Eingecheckt werden nur diese Unterschiede (Block-IDs und Eigenschaftslisten), keine Dateien von Mojang.
//
//   scripts/gen/fetch_version_reports.sh /tmp/mcv          # lädt Server, erzeugt reports/blocks.json je Version
//   node scripts/gen/gen_version_compat.mjs /tmp/mcv       # schreibt packages/voxel/src/versionCompatData.ts
//
// Bezug ist der Blockbericht des Versionsprofils (blockFacts.ts, BLOCK_FACTS_REPORT_SHA256); das Skript bricht
// ab, wenn der Bericht im Ordner <profilversion>/ nicht genau dieser ist.
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) { console.error('Aufruf: gen_version_compat.mjs <ordner mit <version>/reports/blocks.json>'); process.exit(2); }
const facts = readFileSync('packages/voxel/src/blockFacts.ts', 'utf8');
const baseVersion = /BLOCK_FACTS_VERSION = '([^']+)'/.exec(facts)[1];
const baseSha = /BLOCK_FACTS_REPORT_SHA256 = '([0-9a-f]{64})'/.exec(facts)[1];
const sha256 = b => createHash('sha256').update(b).digest('hex');
const bare = id => id.replace(/^minecraft:/, '');

function read(version) {
  const raw = readFileSync(join(dir, version, 'reports/blocks.json'));
  const game = JSON.parse(readFileSync(join(dir, version, 'game_version.json'), 'utf8'));
  const blocks = new Map(Object.entries(JSON.parse(raw.toString('utf8'))).map(([id, b]) => [bare(id), b.properties ?? {}]));
  const defaults = new Map(Object.entries(JSON.parse(raw.toString('utf8'))).map(([id, b]) => [bare(id), b.states.find(s => s.default)?.properties ?? {}]));
  return { version, sha: sha256(raw), dataVersion: game.world_version, serverSha1: readFileSync(join(dir, version, 'server.sha1'), 'utf8').trim(), blocks, defaults };
}

const base = read(baseVersion);
if (base.sha !== baseSha) { console.error(`Blockbericht ${baseVersion} passt nicht zu blockFacts.ts (${base.sha} ≠ ${baseSha})`); process.exit(1); }
const versions = readdirSync(dir).filter(v => v !== baseVersion && existsSync(join(dir, v, 'reports/blocks.json')))
  .map(read).sort((a, b) => b.dataVersion - a.dataVersion);

const props = p => Object.keys(p).sort().map(k => `${k}=${p[k].join(',')}`).join(';');
const lines = [];
lines.push(`// Generated by scripts/gen/gen_version_compat.mjs from the official Minecraft server data generator (reports/blocks.json)`);
lines.push(`// of each listed version, compared with the version profile ${baseVersion} (blockFacts.ts). Facts only: block ids and`);
lines.push(`// property lists that differ. Do not edit by hand; regenerate with a new profile or target version (COMPAT-01).`);
lines.push('');
lines.push(`export const COMPAT_BASE_VERSION = '${baseVersion}';`);
lines.push(`export const COMPAT_BASE_REPORT_SHA256 = '${baseSha}';`);
lines.push('');
lines.push('export interface CompatVersionData {');
lines.push('  readonly version: string;');
lines.push('  readonly dataVersion: number;');
lines.push('  /** SHA-1 of the official server.jar and SHA-256 of its blocks report. */');
lines.push('  readonly serverSha1: string;');
lines.push('  readonly reportSha256: string;');
lines.push(`  /** Blocks of ${baseVersion} that this version does not have, bare ids, newline separated. */`);
lines.push('  readonly missing: string;');
lines.push(`  /** Blocks of both versions whose properties differ: \`id|prop=v1,v2;…|default\` with this version's properties and default state. */`);
lines.push('  readonly changed: string;');
lines.push('}');
lines.push('');
lines.push('/** Newest first. */');
lines.push('export const COMPAT_VERSIONS: readonly CompatVersionData[] = [');
for (const v of versions) {
  const missing = [...base.blocks.keys()].filter(id => !v.blocks.has(id)).sort();
  const changed = [...base.blocks.keys()].filter(id => v.blocks.has(id) && props(v.blocks.get(id)) !== props(base.blocks.get(id))).sort()
    .map(id => `${id}|${props(v.blocks.get(id))}|${Object.keys(v.defaults.get(id)).sort().map(k => `${k}=${v.defaults.get(id)[k]}`).join(',')}`);
  lines.push(`  { version: '${v.version}', dataVersion: ${v.dataVersion}, serverSha1: '${v.serverSha1}', reportSha256: '${v.sha}',`);
  lines.push(`    missing: ${JSON.stringify(missing.join('\n'))},`);
  lines.push(`    changed: ${JSON.stringify(changed.join('\n'))} },`);
  console.log(`${v.version} (DataVersion ${v.dataVersion}): ${missing.length} fehlen, ${changed.length} mit anderen Eigenschaften`);
}
lines.push('];');
lines.push('');
writeFileSync('packages/voxel/src/versionCompatData.ts', lines.join('\n'));
console.log('packages/voxel/src/versionCompatData.ts geschrieben');
