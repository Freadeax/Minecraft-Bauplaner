#!/usr/bin/env node
// Generates packages/formats/src/defaultStates.ts from the block report of the official
// Minecraft server data generator (WORLD-IMPORT-01). The report is not committed.
//
//   java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar --reports --output out
//   node scripts/gen_default_states.mjs out/reports/blocks.json 26.3 5023 <server.jar sha1>
//
// Since 26.x chunk palettes store a block in its default state as the bare id; the reader
// needs the default property values to keep the complete state.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const [report, version, dataVersion, serverSha1] = process.argv.slice(2);
if (!report || !version || !/^\d+$/.test(dataVersion ?? '') || !/^[0-9a-f]{40}$/.test(serverSha1 ?? '')) {
  console.error('Aufruf: gen_default_states.mjs <blocks.json> <version> <dataVersion> <server.jar sha1>'); process.exit(2);
}
const bytes = readFileSync(report);
const blocks = JSON.parse(bytes.toString('utf8'));
const lines = [];
for (const id of Object.keys(blocks).sort()) {
  const d = blocks[id];
  if (!id.startsWith('minecraft:')) throw new Error(`Unerwartete ID ${id}`);
  if (!d.properties) continue;
  const def = d.states.filter(s => s.default);
  if (def.length !== 1) throw new Error(`${id}: genau ein Standardzustand erwartet`);
  lines.push(`${id.slice(10)}|${Object.keys(def[0].properties).sort().map(k => `${k}=${def[0].properties[k]}`).join(',')}`);
}
const sha = createHash('sha256').update(bytes).digest('hex');
const out = `// Generated by scripts/gen_default_states.mjs from the block report of the official Minecraft
// ${version} server data generator (server.jar SHA-1 ${serverSha1}, blocks.json SHA-256 ${sha}).
// Facts only: the default property values of every vanilla block that has properties.
// Do not edit by hand; regenerate for a new profile version.

export const DEFAULT_STATES_VERSION = '${version}';
export const DEFAULT_STATES_DATA_VERSION = ${Number(dataVersion)};
export const DEFAULT_STATES_REPORT_SHA256 = '${sha}';

/** One block per line: \`name|prop=value,…\` (default state). Blocks without properties are absent. */
const DATA = \`${lines.join('\n')}\`;

let parsed: ReadonlyMap<string, Readonly<Record<string, string>>> | null = null;
function table(): ReadonlyMap<string, Readonly<Record<string, string>>> {
  if (parsed) return parsed;
  const map = new Map<string, Readonly<Record<string, string>>>();
  for (const line of DATA.split('\\n')) {
    const [name, spec] = line.split('|') as [string, string];
    const props: Record<string, string> = Object.create(null);
    for (const pair of spec.split(',')) { const [k, v] = pair.split('=') as [string, string]; props[k] = v; }
    map.set(\`minecraft:\${name}\`, Object.freeze(props));
  }
  return parsed = map;
}

/** Default property values of a vanilla block, undefined for unknown ids and blocks without properties. */
export function defaultProperties(id: string): Readonly<Record<string, string>> | undefined { return table().get(id); }
/** Number of blocks with properties in the table (report check). */
export function defaultStateCount(): number { return table().size; }
`;
writeFileSync(new URL('../packages/formats/src/defaultStates.ts', import.meta.url), out);
console.log(`${lines.length} Standardzustände geschrieben (Bericht ${sha.slice(0, 12)}).`);
